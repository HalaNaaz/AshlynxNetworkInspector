import collections
import html
import re
import threading
from datetime import datetime, timezone
from typing import Dict, List, Optional
from backend.app.schemas.security import (
    SecurityEventItem,
    SecurityEventsListResponse,
    SecurityOverviewResponse,
    SecurityStatusResponse,
    SecurityTimelinePoint,
    SecurityTimelineResponse,
    TopThreatSourceItem,
)


def sanitize_text(text: str) -> str:
    """Sanitizes user-supplied input to prevent HTML/XSS injection and bounded length."""
    if not text:
        return ""
    # Strip HTML tags
    clean = re.sub(r"<[^>]*>", "", text)
    # Escape entities
    escaped = html.escape(clean.strip())
    # Bound to 1000 characters
    return escaped[:1000]


class EventManager:
    """Thread-safe security event lifecycle repository with bounded retention and audit logging."""

    def __init__(self, max_events: int = 1000):
        self.max_events = max_events
        self._lock = threading.RLock()
        self._events: Dict[str, SecurityEventItem] = {}
        # Chronological index of event IDs
        self._order: collections.deque = collections.deque()

    def record_event(self, event: SecurityEventItem) -> SecurityEventItem:
        """Stores a new security event with bounded FIFO eviction."""
        with self._lock:
            if event.event_id in self._events:
                # Deduplicated trigger: update counts & last seen
                existing = self._events[event.event_id]
                existing.last_seen = event.last_seen
                existing.observation_count += 1
                return existing

            # Evict oldest resolved or low-severity event if full
            if len(self._events) >= self.max_events:
                self._evict_oldest_event()

            # Record initial audit entry
            now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
            event.audit_trail.append(f"[{now_iso}] Detection event generated by {event.rule_id}.")

            self._events[event.event_id] = event
            self._order.append(event.event_id)
            return event

    def _evict_oldest_event(self) -> None:
        """Evicts oldest resolved event or earliest event from memory."""
        resolved = [eid for eid, ev in self._events.items() if ev.status in ("RESOLVED", "FALSE_POSITIVE")]
        if resolved:
            victim_id = resolved[0]
        elif self._order:
            victim_id = self._order.popleft()
        else:
            victim_id = next(iter(self._events))

        self._events.pop(victim_id, None)

    def get_event(self, event_id: str) -> Optional[SecurityEventItem]:
        with self._lock:
            return self._events.get(event_id)

    def update_status(self, event_id: str, new_status: str, analyst_name: Optional[str] = None) -> Optional[SecurityEventItem]:
        """Audited lifecycle transition."""
        valid_statuses = ("NEW", "ACKNOWLEDGED", "INVESTIGATING", "RESOLVED", "FALSE_POSITIVE")
        clean_status = (new_status or "").strip().upper()
        if clean_status not in valid_statuses:
            raise ValueError(f"Invalid status '{new_status}'. Allowed: {', '.join(valid_statuses)}")

        analyst = sanitize_text(analyst_name or "Security Analyst")[:50]
        now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        with self._lock:
            event = self._events.get(event_id)
            if not event:
                return None
            old_status = event.status
            event.status = clean_status
            event.audit_trail.append(f"[{now_iso}] Status changed from {old_status} to {clean_status} by {analyst}.")
            return event

    def add_note(self, event_id: str, note_text: str, author: Optional[str] = None) -> Optional[SecurityEventItem]:
        """Appends a validated, sanitized analyst note."""
        sanitized = sanitize_text(note_text)
        if not sanitized:
            raise ValueError("Analyst note cannot be empty.")

        analyst = sanitize_text(author or "Security Analyst")[:50]
        now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        with self._lock:
            event = self._events.get(event_id)
            if not event:
                return None
            event.analyst_notes.append(f"[{now_iso} - {analyst}]: {sanitized}")
            event.audit_trail.append(f"[{now_iso}] Note added by {analyst}.")
            return event

    def list_events(
        self,
        session_id: Optional[str] = None,
        severity: Optional[str] = None,
        category: Optional[str] = None,
        status: Optional[str] = None,
        source_ip: Optional[str] = None,
        offset: int = 0,
        limit: int = 50,
    ) -> SecurityEventsListResponse:
        """Filters and paginates security events."""
        with self._lock:
            filtered = list(self._events.values())

        if session_id and session_id.lower() not in ("latest", "all", "*"):
            filtered = [e for e in filtered if e.session_id == session_id]
        if severity and severity.upper() != "ALL":
            filtered = [e for e in filtered if e.severity.upper() == severity.upper()]
        if category and category.upper() != "ALL":
            filtered = [e for e in filtered if e.category.upper() == category.upper()]
        if status and status.upper() != "ALL":
            filtered = [e for e in filtered if e.status.upper() == status.upper()]
        if source_ip and source_ip.strip():
            filtered = [e for e in filtered if e.source_ip == source_ip.strip()]

        # Sort reverse chronologically
        filtered.sort(key=lambda e: e.last_seen, reverse=True)
        total = len(filtered)
        paginated = filtered[offset : offset + limit]

        return SecurityEventsListResponse(
            total=total,
            session_id=session_id,
            events=paginated,
        )

    def get_overview(self, session_id: Optional[str] = None, baseline_manager=None) -> SecurityOverviewResponse:
        """Computes executive security posture overview."""
        with self._lock:
            events = list(self._events.values())

        if session_id and session_id.lower() not in ("latest", "all", "*"):
            events = [e for e in events if e.session_id == session_id]

        total = len(events)
        crit = sum(1 for e in events if e.severity == "CRITICAL")
        high = sum(1 for e in events if e.severity == "HIGH")
        med = sum(1 for e in events if e.severity == "MEDIUM")
        low = sum(1 for e in events if e.severity == "LOW")
        info = sum(1 for e in events if e.severity == "INFO")

        active_inv = sum(1 for e in events if e.status in ("ACKNOWLEDGED", "INVESTIGATING"))
        resolved = sum(1 for e in events if e.status in ("RESOLVED", "FALSE_POSITIVE"))

        # Category breakdown
        cat_counts: Dict[str, int] = {}
        for e in events:
            cat_counts[e.category] = cat_counts.get(e.category, 0) + 1

        # Top sources
        src_map: Dict[str, dict] = {}
        for e in events:
            if not e.source_ip:
                continue
            if e.source_ip not in src_map:
                src_map[e.source_ip] = {"count": 0, "highest": e.severity, "rules": set()}
            src_map[e.source_ip]["count"] += 1
            src_map[e.source_ip]["rules"].add(e.rule_id)
            # Escalate highest
            sev_order = ["INFO", "LOW", "MEDIUM", "HIGH", "CRITICAL"]
            if sev_order.index(e.severity) > sev_order.index(src_map[e.source_ip]["highest"]):
                src_map[e.source_ip]["highest"] = e.severity

        top_sources = [
            TopThreatSourceItem(
                source_ip=ip,
                event_count=data["count"],
                highest_severity=data["highest"],
                associated_rules=sorted(list(data["rules"])),
            )
            for ip, data in sorted(src_map.items(), key=lambda kv: kv[1]["count"], reverse=True)[:5]
        ]

        b_status = baseline_manager.status if baseline_manager else "READY"
        b_samples = baseline_manager.sample_count if baseline_manager else 0
        b_min = baseline_manager.min_samples if baseline_manager else 10

        status_obj = SecurityStatusResponse(
            is_enabled=True,
            active_rules_count=10,
            baseline_status=b_status,
            baseline_samples=b_samples,
            baseline_min_samples=b_min,
            total_events_detected=total,
            critical_events=crit,
            high_events=high,
            medium_events=med,
            low_events=low,
            info_events=info,
            active_investigations=active_inv,
            resolved_events=resolved,
        )

        recent = sorted(events, key=lambda e: e.last_seen, reverse=True)[:5]

        return SecurityOverviewResponse(
            session_id=session_id,
            status=status_obj,
            category_breakdown=cat_counts,
            top_sources=top_sources,
            recent_events=recent,
        )

    def get_timeline(self, session_id: Optional[str] = None) -> SecurityTimelineResponse:
        """Computes time series of security events."""
        with self._lock:
            events = list(self._events.values())

        if session_id and session_id.lower() not in ("latest", "all", "*"):
            events = [e for e in events if e.session_id == session_id]

        bucket_map: Dict[int, dict] = {}
        for e in events:
            # 5-second bucket epoch
            sec = int(e.last_seen.timestamp() // 5 * 5)
            if sec not in bucket_map:
                bucket_map[sec] = {"crit": 0, "high": 0, "med": 0, "low": 0, "info": 0}
            if e.severity == "CRITICAL":
                bucket_map[sec]["crit"] += 1
            elif e.severity == "HIGH":
                bucket_map[sec]["high"] += 1
            elif e.severity == "MEDIUM":
                bucket_map[sec]["med"] += 1
            elif e.severity == "LOW":
                bucket_map[sec]["low"] += 1
            else:
                bucket_map[sec]["info"] += 1

        points: List[SecurityTimelinePoint] = []
        for sec in sorted(bucket_map.keys()):
            counts = bucket_map[sec]
            dt = datetime.fromtimestamp(sec, tz=timezone.utc)
            points.append(
                SecurityTimelinePoint(
                    timestamp=dt,
                    critical_count=counts["crit"],
                    high_count=counts["high"],
                    medium_count=counts["med"],
                    low_count=counts["low"],
                    info_count=counts["info"],
                )
            )

        return SecurityTimelineResponse(total_points=len(points), points=points)
