class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and render exact total page counts (Page X of Y)."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(COLOR_SECONDARY)

        # Running Top Header (Pages 2+)
        if self._pageNumber > 1:
            self.drawString(40, letter[1] - 30, f"{settings.app_name.upper()} — EXECUTIVE AUDIT REPORT")
            self.drawRightString(letter[0] - 40, letter[1] - 30, "CONFIDENTIAL / INTERNAL")
            self.setStrokeColor(COLOR_MUTED)
            self.setLineWidth(0.75)
            self.line(40, letter[1] - 35, letter[0] - 40, letter[1] - 35)

        # Running Bottom Footer
        self.setStrokeColor(COLOR_MUTED)
        self.setLineWidth(0.75)
        self.line(40, 42, letter[0] - 40, 42)

        self.setFont("Helvetica", 8)
        self.setFillColor(COLOR_TEXT_DARK)
        self.drawString(40, 30, f"Generated by {settings.app_name} v{settings.app_version} | SECURE BY DESIGN")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 40, 30, page_str)
        self.restoreState()


class PdfReportGenerator:
    """Produces publication-grade 10-section security audit documents in PDF format."""

    @classmethod
    def generate(cls, payload: ReportPayload) -> bytes:
        buffer = io.BytesIO()

        # Target printable margins: 40pt (0.55 in)
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=40,
            rightMargin=40,
            topMargin=45,
            bottomMargin=48,
        )

        styles = getSampleStyleSheet()

        # Custom Typography Styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=18,
            leading=22,
            textColor=COLOR_PRIMARY,
            spaceAfter=4,
        )
        subtitle_style = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=COLOR_SECONDARY,
            spaceAfter=10,
        )
        section_heading = ParagraphStyle(
            "SectionHeading",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=11,
            leading=14,
            textColor=COLOR_PRIMARY,
            spaceBefore=10,
            spaceAfter=4,
        )
        body_style = ParagraphStyle(
            "ReportBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=12,
            textColor=COLOR_TEXT_DARK,
        )
        table_cell_style = ParagraphStyle(
            "TableCell",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=7.5,
            leading=10,
            textColor=COLOR_TEXT_DARK,
        )
        table_cell_bold = ParagraphStyle(
            "TableCellBold",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=7.5,
            leading=10,
            textColor=COLOR_PRIMARY,
        )
        badge_style = ParagraphStyle(
            "BadgeStyle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=7,
            leading=9,
            textColor=COLOR_WHITE,
            alignment=1,
        )

        story = []

        # ==========================================
        # SECTION 1: HEADER BANNER & DOCUMENT META
        # ==========================================
        banner_data = [
            [
                Paragraph(
                    f"<b>{settings.app_name.upper()}</b><br/><font size=7 color='#457B9D'>NETWORK SECURITY INSPECTOR & PACKET INTELLIGENCE</font>",
                    title_style,
                ),
                Paragraph(
                    f"<b>CLASSIFICATION:</b> <font color='#E63946'><b>CONFIDENTIAL</b></font><br/>"
                    f"<b>REPORT ID:</b> {payload.source_id[:16]}<br/>"
                    f"<b>DATE (UTC):</b> {payload.generated_at.strftime('%Y-%m-%d %H:%M:%S')}",
                    subtitle_style,
                ),
            ]
        ]
        banner_table = Table(banner_data, colWidths=[330, 202])
        banner_table.setStyle(
            TableStyle(
                [
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
                    ("TOPPADDING", (0, 0), (-1, -1), 0),
                    ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ]
            )
        )
        story.append(banner_table)
        story.append(Spacer(1, 6))

        # Title Block
        story.append(Paragraph(payload.title, title_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=COLOR_PRIMARY, spaceBefore=4, spaceAfter=8))

        # ==========================================
        # SECTION 2: EXECUTIVE SUMMARY
        # ==========================================
        story.append(Paragraph("1. EXECUTIVE AUDIT SUMMARY", section_heading))
        summary_p = Paragraph(payload.executive_summary, body_style)
        summary_table = Table([[summary_p]], colWidths=[532])
        summary_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                    ("BOX", (0, 0), (-1, -1), 1, COLOR_PRIMARY),
                    ("TOPPADDING", (0, 0), (-1, -1), 8),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                    ("LEFTPADDING", (0, 0), (-1, -1), 10),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ]
            )
        )
        story.append(summary_table)
        story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 3: SCOPE & TARGET INVENTORY
        # ==========================================
        story.append(Paragraph("2. SCOPE & AUDIT TARGET INVENTORY", section_heading))
        scope_rows = []
        scope_items = list(payload.scope_info.items())
        for i in range(0, len(scope_items), 2):
            k1, v1 = scope_items[i]
            k2, v2 = scope_items[i + 1] if i + 1 < len(scope_items) else ("", "")
            scope_rows.append(
                [
                    Paragraph(f"<b>{k1}:</b>", table_cell_bold),
                    Paragraph(str(v1), table_cell_style),
                    Paragraph(f"<b>{k2}:</b>" if k2 else "", table_cell_bold),
                    Paragraph(str(v2) if k2 else "", table_cell_style),
                ]
            )
        scope_table = Table(scope_rows, colWidths=[110, 156, 110, 156])
        scope_table.setStyle(
            TableStyle(
                [
                    ("GRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
                    ("BACKGROUND", (0, 0), (0, -1), COLOR_BG_LIGHT),
                    ("BACKGROUND", (2, 0), (2, -1), COLOR_BG_LIGHT),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ]
            )
        )
        story.append(scope_table)
        story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 4: KEY METRICS SUMMARY GRID
        # ==========================================
        story.append(Paragraph("3. KEY PERFORMANCE & SECURITY METRICS", section_heading))
        metric_items = list(payload.summary_metrics.items())
        cols_per_row = 3 if len(metric_items) > 4 else 4
        col_w = 532.0 / cols_per_row
        col_widths = [col_w] * cols_per_row

        card_rows = []
        for i in range(0, len(metric_items), cols_per_row):
            chunk = metric_items[i : i + cols_per_row]
            row_cells = []
            for key, val in chunk:
                card_content = [
                    Paragraph(f"<font color='#457B9D'><b>{key.upper()}</b></font>", subtitle_style),
                    Paragraph(f"<font size=13 color='#1D3557'><b>{val}</b></font>", title_style),
                ]
                row_cells.append(card_content)
            while len(row_cells) < cols_per_row:
                row_cells.append([Paragraph("", body_style)])
            card_rows.append(row_cells)

        metrics_table = Table(card_rows, colWidths=col_widths)
        metrics_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), COLOR_WHITE),
                    ("BOX", (0, 0), (-1, -1), 1, COLOR_PRIMARY),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                    ("LEFTPADDING", (0, 0), (-1, -1), 8),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ]
            )
        )
        story.append(metrics_table)
        story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 5: PRIMARY FINDINGS TABLE
        # ==========================================
        story.append(Paragraph("4. PRIMARY AUDIT FINDINGS", section_heading))
        max_rows = 80
        table_data = []

        # Header row
        hdr_cells = [Paragraph(f"<b><font color='white'>{h}</font></b>", table_cell_bold) for h in payload.table_headers]
        table_data.append(hdr_cells)

        # Data rows
        for r_idx, row in enumerate(payload.table_rows[:max_rows]):
            row_cells = []
            for c in row:
                c_str = str(c) if c is not None else "—"
                # Highlight states
                if c_str in ("OPEN", "CRITICAL", "HIGH", "online"):
                    cell_p = Paragraph(f"<font color='#E63946'><b>{c_str}</b></font>", table_cell_bold)
                elif c_str in ("CLOSED", "RESOLVED", "HEALTHY"):
                    cell_p = Paragraph(f"<font color='#2A9D8F'><b>{c_str}</b></font>", table_cell_style)
                else:
                    cell_p = Paragraph(c_str, table_cell_style)
                row_cells.append(cell_p)
            table_data.append(row_cells)

        if not payload.table_rows:
            table_data.append([Paragraph("<i>No line items recorded for this audit scope.</i>", table_cell_style)] * len(payload.table_headers))

        # Distribute column widths dynamically
        num_cols = len(payload.table_headers)
        col_width = 532.0 / num_cols
        col_widths = [col_width] * num_cols

        findings_table = Table(table_data, colWidths=col_widths, repeatRows=1)
        t_style = [
            ("BACKGROUND", (0, 0), (-1, 0), COLOR_PRIMARY),
            ("BOX", (0, 0), (-1, -1), 1, COLOR_PRIMARY),
            ("GRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]
        # Alternating zebra rows
        for i in range(1, len(table_data)):
            if i % 2 == 0:
                t_style.append(("BACKGROUND", (0, i), (-1, i), COLOR_BG_LIGHT))
        findings_table.setStyle(TableStyle(t_style))

        story.append(findings_table)
        if len(payload.table_rows) > max_rows:
            story.append(Paragraph(f"<i>Table truncated for print readability. Showing {max_rows} of {len(payload.table_rows)} findings. Export CSV or JSON for full recordset.</i>", subtitle_style))
        story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 6: TELEMETRY & PROTOCOL ANALYSIS
        # ==========================================
        if payload.telemetry_details:
            story.append(Paragraph("5. WIRE TELEMETRY & TRAFFIC BREAKDOWN", section_heading))
            telemetry_rows = [
                [Paragraph(f"<b>{k}:</b>", table_cell_bold), Paragraph(str(v), table_cell_style)]
                for k, v in payload.telemetry_details.items()
            ]
            tele_table = Table(telemetry_rows, colWidths=[200, 332])
            tele_table.setStyle(
                TableStyle(
                    [
                        ("GRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
                        ("BACKGROUND", (0, 0), (0, -1), COLOR_BG_LIGHT),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                        ("LEFTPADDING", (0, 0), (-1, -1), 6),
                    ]
                )
            )
            story.append(tele_table)
            story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 7: SECURITY & RISK ASSESSMENT
        # ==========================================
        story.append(Paragraph("6. SECURITY & RISK POSTURE EVALUATION", section_heading))
        sec_rows = [
            [Paragraph(f"<b>{k}:</b>", table_cell_bold), Paragraph(str(v), table_cell_style)]
            for k, v in payload.security_posture.items()
        ]
        sec_table = Table(sec_rows, colWidths=[200, 332])
        sec_table.setStyle(
            TableStyle(
                [
                    ("GRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
                    ("BACKGROUND", (0, 0), (0, -1), COLOR_BG_LIGHT),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ]
            )
        )
        story.append(sec_table)
        story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 8: OPERATIONAL RECOMMENDATIONS
        # ==========================================
        story.append(Paragraph("7. OPERATIONAL REMEDIATION & HARDENING", section_heading))
        rec_cells = []
        for idx, rec in enumerate(payload.recommendations, start=1):
            rec_p = Paragraph(f"<b>{idx}.</b> {rec}", body_style)
            rec_cells.append([rec_p])
        rec_table = Table(rec_cells, colWidths=[532])
        rec_table.setStyle(
            TableStyle(
                [
                    ("BOX", (0, 0), (-1, -1), 1, COLOR_PRIMARY),
                    ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 8),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ]
            )
        )
        story.append(rec_table)
        story.append(Spacer(1, 8))

        # ==========================================
        # SECTION 9: AUDITOR & SYSTEM SIGN-OFF BLOCK
        # ==========================================
        signoff_data = [
            [
                Paragraph("<b>SYSTEM VERIFICATION & SIGN-OFF</b>", table_cell_bold),
                Paragraph("<b>AUDITOR INTEGRITY CONFIRMATION</b>", table_cell_bold),
            ],
            [
                Paragraph(
                    f"Platform: {settings.app_name} v{settings.app_version}<br/>"
                    f"Architecture: Dual-Engine Port Scanner & Traffic Analyzer<br/>"
                    f"Integrity Check: PASSED (Automated Session Digest)",
                    table_cell_style,
                ),
                Paragraph(
                    f"Audit Scope: Authorized Workstation Assessment<br/>"
                    f"Safe Mode: ENFORCED<br/>"
                    f"Timestamp: {payload.generated_at.isoformat()}",
                    table_cell_style,
                ),
            ],
        ]
        signoff_table = Table(signoff_data, colWidths=[266, 266])
        signoff_table.setStyle(
            TableStyle(
                [
                    ("BOX", (0, 0), (-1, -1), 1, COLOR_PRIMARY),
                    ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_LIGHT),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_MUTED),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 8),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ]
            )
        )
        story.append(KeepTogether([signoff_table]))

        # SECTION 10: Canvas callbacks handle the running header and footer numbering (Page X of Y)
        doc.build(story, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer.getvalue()

