class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and render exact total page counts (Page X of Y)."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(COLOR_SECONDARY)

        # Running Top Header (Pages 2+)
        if self._pageNumber > 1:
            self.drawString(40, letter[1] - 30, f"{settings.app_name.upper()} — EXECUTIVE AUDIT REPORT")
            self.drawRightString(letter[0] - 40, letter[1] - 30, "CONFIDENTIAL / INTERNAL")
            self.setStrokeColor(COLOR_MUTED)
            self.setLineWidth(0.75)
            self.line(40, letter[1] - 35, letter[0] - 40, letter[1] - 35)

        # Running Bottom Footer
        self.setStrokeColor(COLOR_MUTED)
        self.setLineWidth(0.75)
        self.line(40, 42, letter[0] - 40, 42)

        self.setFont("Helvetica", 8)
        self.setFillColor(COLOR_TEXT_DARK)
        self.drawString(40, 30, f"Generated by {settings.app_name} v{settings.app_version} | SECURE BY DESIGN")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 40, 30, page_str)
        self.restoreState()


